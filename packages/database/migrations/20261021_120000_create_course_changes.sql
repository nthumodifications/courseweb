create table if not exists public.course_changes (
  id bigint generated by default as identity primary key,
  raw_id text not null references public.courses(raw_id),
  semester text not null,
  field text not null,
  old_value jsonb,
  new_value jsonb,
  kind text not null,
  detected_at timestamptz not null default now(),
  constraint course_changes_kind_check
    check (kind in ('changed', 'removed', 'reappeared'))
);

create index if not exists course_changes_raw_id_detected_at_idx
  on public.course_changes (raw_id, detected_at desc);

create index if not exists course_changes_semester_detected_at_idx
  on public.course_changes (semester, detected_at desc);

alter table public.course_changes enable row level security;

revoke all on table public.course_changes from anon, authenticated;
grant select on table public.course_changes to anon, authenticated;

create policy "Course changes are publicly readable"
  on public.course_changes
  for select
  to anon, authenticated
  using (true);
